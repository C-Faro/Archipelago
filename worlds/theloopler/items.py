class TheLooplerItem(Item):
    game = "The Loopler"

def get_random_filler_item_name(world: TheLooplerWorld) -> str:
    if world.random.randint(0, 99) < world.options.trap_chance:
        return world.random.choice(sorted(TRAP_TABLE))
    return world.random.choice(sorted(FILLER_TABLE))

def create_item_with_correct_classification(world: TheLooplerWorld, name: str) -> TheLooplerItem:
    classification = DEFAULT_ITEM_CLASSIFICATION[name]

    return TheLooplerItem(name, classification, ITEM_NAME_TO_ID[name], world.player)

def create_all_items(world: TheLooplerWorld) -> None:
    itempool: list[Item] = []

    for item_name in sorted(ITEM_TABLE):
        itempool.append(world.create_item(item_name))

    if world.options.starting_items_rando:
        starting_loop = world.create_item(world.random.choice(sorted(LOOP_TABLE)))
        starting_track = world.create_item(world.random.choice(sorted(TRACK_TABLE)))
        starting_car = world.create_item(world.random.choice(sorted(CAR_TABLE)))
    else:
        starting_loop = world.create_item("Loop: Bronze Loop")
        starting_track = world.create_item("Track: Infinity Track")
        starting_car = world.create_item("Car: Dura Car")

    starting_items = {starting_track, starting_car, starting_loop}

    for item in starting_items:
        world.push_precollected(item)

    world.starting_item_names = {item for item in starting_items}

    for item in starting_items:
        itempool.remove(item)

    number_of_items = len(itempool)

    number_of_unfilled_locations = len(world.multiworld.get_unfilled_locations(world.player))

    needed_number_of_filler = number_of_unfilled_locations - number_of_items

    itempool += [world.create_filler() for _ in range(needed_number_of_filler)]

    world.multiworld.itempool += itempool